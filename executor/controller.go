// ControllerDrainCapability identifies authenticated single-controller admission
// with joined foreground callbacks. It does not imply descendant-process or
// external-effect quiescence.
const ControllerDrainCapability = "controller-drain.v2"

// ControllerCredentialHeader carries an opaque, purpose-limited host admission.
// It must not contain a shell callback token or an unverified ownership claim.
const ControllerCredentialHeader = "X-Sol-Controller-Credential"

var (
	ErrControllerReplaced = errors.New("executor controller superseded; request outcome may be unknown")
	ErrControllerClosed   = errors.New("executor controller supervisor closed")
)

// ControllerIdentity names a resource incarnation and this server process.
// BootID is generated by the server, not supplied by a connecting controller.
// The host must register it through its trusted resource initialization path;
// accepting an unregistered BootID would permit stale admission after restart.
type ControllerIdentity struct {
	ResourceID  string `json:"resource_id"`
	Incarnation string `json:"incarnation"`
	BootID      string `json:"boot_id"`
}

// ControllerGrant is returned by the trusted authority, never decoded from an
// unchecked client assertion. Epochs increase for every socket admission,
// including reconnects by the same owner. An admission is consumed even when
// its handshake acknowledgement is lost; reconnect requires a fresh admission.
type ControllerGrant struct {
	Epoch       uint64    `json:"epoch"`
	AdmissionID string    `json:"admission_id"`
	ValidUntil  time.Time `json:"valid_until"`
}

// ControllerStatus describes admission only, never a command's outcome. A lost
// READY can be inspected without opening a replacement socket or replaying work.
type ControllerStatus struct {
	Identity ControllerIdentity `json:"identity"`
	Grant    ControllerGrant    `json:"grant"`
	Phase    string             `json:"phase"` // draining, active, consumed, superseded, closed
}

// ControllerStatusHandler returns a read-only, authenticated status endpoint.
// The embedding host chooses its route. Status cannot reattach a socket: even an
// active equal-epoch admission requires a fresh grant to replace a lost socket.
func (s *ToolServer) ControllerStatusHandler() http.Handler {
	if s.controller == nil {
		panic("executor: controller status requires a controlled server")
	}
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Method != http.MethodGet {
			w.WriteHeader(http.StatusMethodNotAllowed)
			return
		}
		c := s.controller
		grant, err := c.validate(r.Context(), r.Header.Get(ControllerCredentialHeader))
		if err != nil {
			http.Error(w, "controller status denied", http.StatusForbidden)
			return
		}
		status := ControllerStatus{Identity: c.identity, Grant: grant, Phase: "superseded"}
		c.mu.Lock()
		switch {
		case c.closed:
			status.Phase = "closed"
		case sameAdmission(grant, c.high):
			status.Phase = "consumed"
			if c.active != nil {
				select {
				case <-c.active.done:
				default:
					status.Phase = "active"
				}
			} else if c.draining != nil {
				select {
				case <-c.draining:
				default:
					status.Phase = "draining"
				}
			}
		}
		c.mu.Unlock()
		w.Header().Set("Content-Type", "application/json")
		_ = json.NewEncoder(w).Encode(status)
	})
}

// ControllerAuthority verifies purpose-limited admission bound to every identity
// field. It runs before takeover and after drain, not before each message. The
// embedding trusted host owns live authorization before sending operations.
// Local ordering covers delivered generations, not undelivered issuer state.
type ControllerAuthority interface {
	Validate(context.Context, ControllerIdentity, string) (ControllerGrant, error)
}

type controllerConnection struct {
	ctx    context.Context
	cancel context.CancelFunc
	done   chan struct{}
	grant  ControllerGrant
}

type controllerSupervisor struct {
	mu        sync.Mutex
	identity  ControllerIdentity
	authority ControllerAuthority
	high      ControllerGrant
	active    *controllerConnection
	draining  <-chan struct{}
	closed    bool
}

// NewControlledToolServer creates a resource-local single-controller server.
// The authority and resource identity are required. Its Handler fails closed
// without a valid controller credential; NewToolServer is the separate,
// explicitly uncontrolled API. A fresh BootID prevents process restart from
// resetting admission ordering under an unchanged authority binding.
func NewControlledToolServer(exec tool.Executor, resourceID, incarnation string, authority ControllerAuthority) *ToolServer {
	if exec == nil || authority == nil || resourceID == "" || incarnation == "" {
		panic("executor: controlled server requires executor, resource identity and authority")
	}
	var nonce [32]byte
	if _, err := rand.Read(nonce[:]); err != nil {
		panic(fmt.Sprintf("executor: generate controller boot identity: %v", err))
	}
	s := NewToolServer(exec)
	s.controller = &controllerSupervisor{
		identity:  ControllerIdentity{ResourceID: resourceID, Incarnation: incarnation, BootID: hex.EncodeToString(nonce[:])},
		authority: authority,
	}
	return s
}

// ControllerIdentity returns the identity for trusted host registration. It is
// not a credential and must not itself grant permission to register a boot.
func (s *ToolServer) ControllerIdentity() ControllerIdentity {
	if s.controller == nil {
		panic("executor: controller identity requires a controlled server")
	}
	return s.controller.identity
}

func (c *controllerSupervisor) validate(ctx context.Context, credential string) (ControllerGrant, error) {
	if credential == "" {
		return ControllerGrant{}, errors.New("controller credential required")
	}
	grant, err := c.authority.Validate(ctx, c.identity, credential)
	if err != nil {
		return ControllerGrant{}, err
	}
	if grant.Epoch == 0 || grant.AdmissionID == "" || !grant.ValidUntil.After(time.Now()) {
		return ControllerGrant{}, errors.New("authority returned invalid or expired controller grant")
	}
	return grant, nil
}

func sameAdmission(a, b ControllerGrant) bool {
	return a.Epoch == b.Epoch && a.AdmissionID == b.AdmissionID
}

// admit records the high-water admission before waiting for foreground drain.
// Concurrent higher admissions supersede a pending lower one. Abandoned or
// rejected post-drain admissions never roll the high-water mark back.
func (c *controllerSupervisor) admit(ctx context.Context, credential string) (*controllerConnection, error) {
	return c.admitWith(ctx, credential, c.validate)
}

func (c *controllerSupervisor) admitWith(ctx context.Context, credential string, validate func(context.Context, string) (ControllerGrant, error)) (*controllerConnection, error) {
	grant, err := validate(ctx, credential)
	if err != nil {
		return nil, err
	}
	if grant.Epoch == 0 || grant.AdmissionID == "" || !grant.ValidUntil.After(time.Now()) {
		return nil, errors.New("invalid controller grant")
	}
	c.mu.Lock()
	if c.closed {
		c.mu.Unlock()
		return nil, ErrControllerClosed
	}
	if grant.Epoch <= c.high.Epoch {
		c.mu.Unlock()
		return nil, ErrControllerReplaced
	}
	c.high = grant
	if c.active != nil {
		// Clearing active fences all old data/control frames before cancellation.
		old := c.active
		c.active = nil
		c.draining = old.done
		old.cancel()
	}
	draining := c.draining
	c.mu.Unlock()

	if draining != nil {
		select {
		case <-draining:
		case <-ctx.Done():
			return nil, ctx.Err()
		}
	}
	current, err := validate(ctx, credential)
	if err != nil {
		return nil, err
	}
	if !sameAdmission(grant, current) {
		return nil, ErrControllerReplaced
	}
	if !current.ValidUntil.After(time.Now()) {
		return nil, errors.New("controller grant expired during drain")
	}
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.closed {
		return nil, ErrControllerClosed
	}
	if !sameAdmission(c.high, grant) {
		return nil, ErrControllerReplaced
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	connectionCtx, cancel := context.WithDeadline(context.Background(), current.ValidUntil)
	conn := &controllerConnection{ctx: connectionCtx, cancel: cancel, done: make(chan struct{}), grant: current}
	c.active = conn
	c.draining = nil
	return conn, nil
}

// checkDispatch is the dispatch linearization point. A dispatch admitted before
// replacement is part of the joined foreground batch even if cancellation races
// its callback entry. No dispatch admitted after replacement can reach a tool,
// attachment materializer or connection control handler.
func (c *controllerSupervisor) checkDispatch(conn *controllerConnection) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.closed || c.active != conn || !sameAdmission(c.high, conn.grant) || conn.ctx.Err() != nil || !conn.grant.ValidUntil.After(time.Now()) {
		conn.cancel()
		return ErrControllerReplaced
	}
	return nil
}

func (s *ToolServer) controlledHandler(w http.ResponseWriter, r *http.Request) {
	if s.bootstrap != nil && !s.bootstrap.Ready() {
		http.Error(w, "workspace initialization required", http.StatusServiceUnavailable)
		return
	}
	conn, err := s.controller.admit(r.Context(), r.Header.Get(ControllerCredentialHeader))
	if err != nil {
		http.Error(w, "controller admission denied", http.StatusForbidden)
		return
	}
	// Closing done belongs exclusively to this handler, after all foreground
	// callbacks return. HTTP cancellation or a failed upgrade cannot skip drain.
	defer close(conn.done)
	defer conn.cancel()
	ws, err := websocket.Accept(w, r, &websocket.AcceptOptions{InsecureSkipVerify: true})
	if err != nil {
		return
	}
	ws.SetReadLimit(maxWSMessageBytes)
	s.handleConnection(conn.ctx, conn.cancel, ws, conn)
}

// ShutdownControllers permanently disables admission, cancels the current
// controller and joins its foreground callbacks. A deadline reports incomplete
// drain; it does not re-enable the resource or claim callback settlement.
// net/http Shutdown does not join hijacked WebSocket connections.
func (s *ToolServer) ShutdownControllers(ctx context.Context) error {
	if s.controller == nil {
		panic("executor: controller shutdown requires a controlled server")
	}
	c := s.controller
	c.mu.Lock()
	c.closed = true
	if c.active != nil {
		old := c.active
		c.active = nil
		c.draining = old.done
		old.cancel()
	}
	draining := c.draining
	c.mu.Unlock()
	if draining == nil {
		return nil
	}
	select {
	case <-draining:
		return nil
	case <-ctx.Done():
		return ctx.Err()
	}
}

func (s *ToolServer) resetControllerState() {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.pm.SetRules(nil)
	s.qm = bus.NewQuestionManager(s.bus)
	s.activeTools = nil
}
